import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import os from 'node:os';
import path from 'node:path';
import { pathToFileURL } from 'node:url';
import { prepareApp, runtimeFiles } from '../scripts/prepare-app.mjs';

test('packaged desktop resolves its own shared core and preserves independent versions without the checkout', async t => {
  const fixture = await fs.mkdtemp(path.join(os.tmpdir(), 'finder-packaging-test-'));
  t.after(() => fs.rm(fixture, { recursive: true, force: true }));
  const repositoryRoot = path.join(fixture, 'source');
  const electronRoot = path.join(repositoryRoot, 'electron');
  const outputDirectory = path.join(fixture, 'standalone');
  await fs.mkdir(electronRoot, { recursive: true });
  const core = JSON.parse(await fs.readFile(new URL('../../package.json', import.meta.url), 'utf8'));
  core.version = '1.2.3';
  await fs.writeFile(path.join(repositoryRoot, 'package.json'), JSON.stringify(core));
  await fs.cp(new URL('../../src/', import.meta.url), path.join(repositoryRoot, 'src'), { recursive: true });
  await fs.cp(new URL('../../bin/', import.meta.url), path.join(repositoryRoot, 'bin'), { recursive: true });
  await fs.writeFile(path.join(electronRoot, 'package.json'), JSON.stringify({ name: 'desktop-fixture', version: '9.8.7', private: true }));
  for (const file of runtimeFiles) await fs.copyFile(new URL(`../${file}`, import.meta.url), path.join(electronRoot, file));
  await fs.cp(new URL('../locales/', import.meta.url), path.join(electronRoot, 'locales'), { recursive: true });
  await fs.mkdir(path.join(electronRoot, 'renderer-dist'));
  await fs.writeFile(path.join(electronRoot, 'renderer-dist/index.html'), '<html>fixture</html>');
  await prepareApp({ repositoryRoot, electronRoot, outputDirectory });
  await fs.rm(repositoryRoot, { recursive: true });
  const desktop = JSON.parse(await fs.readFile(path.join(outputDirectory, 'package.json'), 'utf8'));
  assert.equal(desktop.version, '9.8.7');
  assert.equal(desktop.dependencies['finder-selection-sync'], '1.2.3');
  const coreDirectory = path.join(outputDirectory, 'node_modules/finder-selection-sync');
  assert.equal((await fs.lstat(coreDirectory)).isSymbolicLink(), false);
  const shared = await import(pathToFileURL(path.join(coreDirectory, 'src/index.js')).href);
  assert.equal(shared.VERSION, '1.2.3');
  const { DesktopService } = await import(pathToFileURL(path.join(outputDirectory, 'service.js')).href);
  const target = path.join(fixture, 'photos');
  await fs.mkdir(target);
  await fs.writeFile(path.join(target, 'A.NEF'), 'reference');
  await fs.writeFile(path.join(target, 'B.JPG'), 'orphan');
  const service = new DesktopService();
  t.after(() => service.discard());
  const plan = await service.preview({ mode: 'orphans', mixed: true, base: target, referenceExt: 'nef' });
  assert.equal(plan.candidates, 1);
  assert.equal(plan.rows.find(row => row.candidate).name, 'B.JPG');
  const filtered = await service.preview({ mode: 'filter', targets: [target], nameRegex: '\\.jpg$', ignoreCase: true });
  assert.equal(filtered.mode, 'filter');
  assert.equal(filtered.candidates, 1);
  assert.equal(filtered.rows.find(row => row.candidate).name, 'B.JPG');
  await assert.rejects(fs.access(path.join(outputDirectory, 'renderer')));
  await assert.rejects(fs.access(path.join(outputDirectory, 'node_modules/electron')));
});
